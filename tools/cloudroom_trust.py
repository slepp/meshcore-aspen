"""Public root list for shared-room links, in the SDK certificate-bundle format.

A node that links to a shared-room service verifies the server against these roots.
The list is the subject name and public key of each root (about 300 bytes each), not
the certificates, so the application image grows by a few kilobytes.

  cloudroom_trust.py generate [--source PEM ...] [--out HEADER]   write the header
  cloudroom_trust.py check [--source PEM ...]                      the committed header is current
  cloudroom_trust.py verify HOST[:PORT]                            check a live server's chain

`generate` and `check` read PEM bundles of public roots (default: the system store and
cloudroom_roots.pem) and keep only roots whose SHA-256 fingerprint matches the one pinned below.
"""
import argparse
import hashlib
import re
import struct
import subprocess
import sys
from pathlib import Path
from cryptography import x509
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec, padding, rsa

HEADER = Path(__file__).resolve().parents[1] / "firmware/esp32/CloudRoomRoots.h"
# The system store first, then roots it may lack (GlobalSign Root CA, which signs the cross
# certificate of GTS Root R4 that Cloudflare sends with every GTS chain).
DEFAULT_SOURCES = [Path("/etc/ssl/certs/ca-certificates.crt"), Path(__file__).with_name("cloudroom_roots.pem")]
# Common name -> SHA-256 of the DER certificate. Cloudflare issues from these authorities.
