PEM = re.compile(r"-----BEGIN CERTIFICATE-----.*?-----END CERTIFICATE-----", re.S)


def der(certificate):
    return certificate.public_bytes(serialization.Encoding.DER)


def common_name(certificate):
    return certificate.subject.get_attributes_for_oid(x509.NameOID.COMMON_NAME)[0].value


def load(sources):
    found = {}
    for source in sources:
        for block in PEM.findall(Path(source).read_text()):
            certificate = x509.load_pem_x509_certificate(block.encode())
            try:
                name = common_name(certificate)
            except IndexError:
                continue
            # Several roots can share a common name; only the pinned one is kept.
            if name in ROOTS and hashlib.sha256(der(certificate)).hexdigest() == ROOTS[name]:
                found[name] = certificate
    missing = sorted(set(ROOTS) - set(found))
    if missing:
        raise SystemExit("roots missing from the source bundle: " + ", ".join(missing))
    return found


def entries(found):
    result = []
    for name, certificate in found.items():
        subject = certificate.subject.public_bytes()
        key = certificate.public_key().public_bytes(serialization.Encoding.DER,
                                                    serialization.PublicFormat.SubjectPublicKeyInfo)
        result.append((subject, key, name, certificate))
    # The SDK looks roots up by binary search on the raw subject name.
    return sorted(result, key=lambda entry: entry[0])


def bundle(found):
    sorted_entries = entries(found)
    blob = bytearray(struct.pack(">H", len(sorted_entries)))
    for subject, key, _, _ in sorted_entries:
        blob += struct.pack(">HH", len(subject), len(key)) + subject + key
    return bytes(blob), sorted_entries


def render(found):
    blob, sorted_entries = bundle(found)
    lines = ["// SPDX-License-Identifier: Apache-2.0",
             "// Generated by tools/cloudroom_trust.py; run it again instead of editing this file.",
             "// Public roots a shared-room link verifies against, in the SDK certificate-bundle format",
             "// (entry count, then subject name and public key of each root sorted by subject name).",
             "//"]
    for _, _, name, certificate in sorted_entries:
        lines.append(f"//   {name}  sha256 {hashlib.sha256(der(certificate)).hexdigest()}  expires {certificate.not_valid_after.date()}")
    lines += ["#pragma once", "#include <stdint.h>", "", "namespace onchip {",
              f"// {len(blob)} bytes, {len(sorted_entries)} roots.",
              "inline constexpr uint8_t cloudRoomRootBundle[] = {"]
    for offset in range(0, len(blob), 16):
        lines.append("    " + ", ".join(f"0x{byte:02x}" for byte in blob[offset:offset + 16]) + ",")
    lines += ["};", "} // namespace onchip", ""]
    return "\n".join(lines)


def chain_of(host, port):
    out = subprocess.run(["openssl", "s_client", "-showcerts", "-servername", host, "-connect", f"{host}:{port}"],
                         input=b"", capture_output=True, timeout=30).stdout.decode("utf-8", "replace")
    return [x509.load_pem_x509_certificate(block.encode()) for block in PEM.findall(out)]


def verify_signature(child, key_der):
    key = serialization.load_der_public_key(key_der)
    if isinstance(key, rsa.RSAPublicKey):
        key.verify(child.signature, child.tbs_certificate_bytes, padding.PKCS1v15(), child.signature_hash_algorithm)
    else:
        key.verify(child.signature, child.tbs_certificate_bytes, ec.ECDSA(child.signature_hash_algorithm))


def parse_bundle(blob):
    """Subject name -> public key, as the SDK reads the list."""
    table = {}
    count = struct.unpack(">H", blob[:2])[0]
    at = 2
    for _ in range(count):
        name_length, key_length = struct.unpack(">HH", blob[at:at + 4])
        table[blob[at + 4:at + 4 + name_length]] = blob[at + 4 + name_length:at + 4 + name_length + key_length]
        at += 4 + name_length + key_length
    if at != len(blob):
        raise ValueError("trailing bytes after the last root")
    return table


def verify_chain(chain, table):
    """Same decision as the SDK verifier: the first link whose issuer is not in the chain must
    be signed by the root whose subject name equals that link's issuer."""
    for index, child in enumerate(chain):
        issuer = child.issuer.public_bytes()
        if index + 1 < len(chain) and chain[index + 1].subject.public_bytes() == issuer:
            verify_signature(child, chain[index + 1].public_key().public_bytes(
                serialization.Encoding.DER, serialization.PublicFormat.SubjectPublicKeyInfo))
            continue
        if issuer in table:
            verify_signature(child, table[issuer])
            return child
        if any(other.subject.public_bytes() == issuer for other in chain):
            continue
        raise ValueError(f"issuer of {child.subject.rfc4514_string()} is not in the root list")
    raise ValueError("the chain never reaches a listed root")


def verify(host, port, found):
    chain = chain_of(host, port)
    if not chain:
        raise SystemExit("no certificate chain received")
    try:
        child = verify_chain(chain, parse_bundle(bundle(found)[0]))
    except ValueError as error:
        raise SystemExit(f"{host}: {error}")
    return common_name(child), child.issuer.public_bytes()


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("command", choices=("generate", "check", "verify"))
    parser.add_argument("target", nargs="?", help="HOST[:PORT] for verify")
    parser.add_argument("--source", action="append", help="PEM bundle of public roots (repeatable)")
    parser.add_argument("--out", default=str(HEADER))
    args = parser.parse_args()
    found = load(args.source or DEFAULT_SOURCES)
    if args.command == "generate":
        Path(args.out).write_text(render(found))
        print(f"wrote {args.out}: {len(bundle(found)[0])} bytes, {len(found)} roots")
    elif args.command == "check":
        if Path(args.out).read_text() != render(found):
            raise SystemExit(f"{args.out} is out of date; run cloudroom_trust.py generate")
        print("header is current")
    else:
        if not args.target:
            parser.error("verify needs HOST[:PORT]")
        host, _, port = args.target.partition(":")
        leaf, issuer = verify(host, int(port or 443), found)
        print(f"{host}: {leaf} chains to a listed root")


if __name__ == "__main__":
    sys.exit(main())
